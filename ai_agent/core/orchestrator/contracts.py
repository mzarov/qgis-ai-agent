from collections.abc import Callable
from typing import TYPE_CHECKING, Any, Protocol

if TYPE_CHECKING:
    from ai_agent.core.agent.loop import AgentLoop
    from ai_agent.core.orchestrator.compacting import SessionCompaction
    from ai_agent.core.orchestrator.naming import SessionNaming
    from ai_agent.core.orchestrator.rewind import Checkpoint
    from ai_agent.core.state.conversation import ConversationState
    from ai_agent.core.usage_stats import UsageStats

RetryArgs = tuple[str, str, str, list[str] | None, list[str] | None, bool]


class DockWidgetContract(Protocol):
    def add_user_message(self, text: str) -> int: ...

    def mark_rewind_point(self, entry_id: int, message: int) -> None: ...

    def choose_rewind(self, project_available: bool) -> str | None: ...

    def add_system_message(self, text: str) -> int: ...

    def add_error_message(self, text: str) -> int: ...

    def add_run_failure(
        self, title: str, detail: str, message: str, kind: str, fixed_in_settings: bool, retryable: bool
    ) -> int: ...

    def drop_failures(self) -> None: ...

    def offer_retry(self) -> None: ...

    def set_run_kind(self, kind: str) -> None: ...

    def add_result_message(self, text: str) -> int: ...

    def add_visual(self, spec: dict[str, Any]) -> int: ...

    def add_question(self, question: str, options: list[str]) -> int: ...

    def add_tool_message(self, text: str) -> int: ...

    def add_stream_chunk(self, text: str) -> None: ...

    def add_thinking_chunk(self, text: str) -> None: ...

    def finish_stream(self, markdown: str) -> bool: ...

    def add_rejected_message(self, text: str) -> int: ...

    def mark_tool_done(self, message_id: int, ok: bool = True, note: str = "") -> None: ...

    def add_plan_message(self, plan_lines: list[str], applies_itself: bool = False, layer: str = "") -> int: ...

    def confirm_data_sharing(self, endpoint: str) -> bool: ...
    def confirm_destructive(self, lines: list[str], details: str = "") -> bool: ...

    def mark_plan_completed(self, message_id: int, undoable: bool = False) -> None: ...

    def mark_plan_failed(self, message_id: int, undoable: bool = False) -> None: ...

    def mark_plan_undone(self, message_id: int) -> None: ...

    def mark_plan_step(self, message_id: int, index: int, state: str, note: str = "") -> None: ...

    def mark_plan_progress(self, message_id: int, index: int, percent: float, done: int = 0) -> None: ...

    def set_project_line(self, text: str) -> None: ...

    def set_model(self, name: str) -> None: ...

    def show_outcome(self, kind: str, summary: str = "") -> None: ...

    def begin_work(self) -> None: ...

    def show_retry(self, seconds: float, attempt: int, total: int, busy: bool) -> None: ...

    def set_conversation_title(self, title: str) -> None: ...

    def note_conversation_saved(self) -> None: ...

    def set_active_layer(self, name: str, detail: str = "") -> None: ...

    def context_mention(self) -> str: ...

    def mark_plan_cancelled(self, message_id: int, restorable: bool = False) -> None: ...

    def mark_plan_restored(self, message_id: int) -> None: ...

    def forget_plan_restore(self, message_id: int) -> None: ...

    def set_busy(self, busy: bool) -> None: ...

    def set_context(self, used: int, window: int, spent: int, requests: int = 0) -> None: ...

    def set_configured(self, configured: bool) -> None: ...

    def clear_prompt(self) -> None: ...

    def replay(self, messages: list[dict[str, Any]]) -> None: ...

    def set_session_source(self, provider: Callable[[], list[tuple[str, str, float, bool]]]) -> None: ...

    def set_skill_source(self, provider: Callable[[], list[tuple[str, str, str]]]) -> None: ...

    def set_layer_source(self, provider: Callable[[], list[tuple[str, str, str]]]) -> None: ...

    def restore_prompt(self, text: str) -> None: ...

    def keep_stream(self) -> str: ...

    def mention_layers(self, names: list[str]) -> None: ...

    def add_attachment(self, path: str) -> None: ...

    def take_attachments(self) -> list[str]: ...

    def set_work_mode(self, mode: str) -> None: ...

    def offer_plan(self) -> None: ...


class OrchestratorHost:
    if TYPE_CHECKING:
        iface: Any
        dock_widget: DockWidgetContract
        conversation: ConversationState
        agent: AgentLoop
        compaction: SessionCompaction
        naming: SessionNaming
        usage: UsageStats
        _active_tool_message_id: int | None
        _plan_message_id: int | None
        _plan_step: int
        _plan_marks: list[list[str]]
        _plan_keys: dict[int, str]
        _plan_snapshots: dict[int, str]
        _restorable_plan_id: int | None
        _apply_scope: tuple[str, str] | None
        _invalidated_scope: tuple[str, str] | None
        _deferred_interrupted_outcome: str
        _checkpoints: list[Checkpoint]
        _snapshot_before_apply: str
        _restoring_snapshot: bool
        _retry_args: RetryArgs | None
        _done_summary: str
        _last_request: str

        @property
        def is_idle(self) -> bool: ...

        def _show_title(self) -> None: ...

        def _push_message(self, text: str, level: Any) -> None: ...

        def _confirm_first_send(self, endpoint: str | None = None) -> bool: ...

        def _start_run(
            self,
            shown: str,
            prompt: str,
            request: str,
            skills: list[str] | None = None,
            images: list[str] | None = None,
        ) -> None: ...

        def _replay(self) -> None: ...

        def _render_answer(self, message: str) -> None: ...

        def on_visual_ready(self, spec: dict[str, Any]) -> None: ...

        def _plan_settled(
            self, state: str, marks: list[list[str]] | None = None, plan_id: int | None = None
        ) -> None: ...

        def _forget_restore(self) -> None: ...

        def _drop_pending_plan(self) -> None: ...

        def _note_apply_start(self) -> None: ...

        def _record_checkpoint(self) -> None: ...
